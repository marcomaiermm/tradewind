// Both languages are declared together: missing keys cannot compile.
use super::Language;
macro_rules! catalog {
    ($( $key:ident => [$en:literal, $de:literal] $(, [$en_many:literal, $de_many:literal])?; )*) => {
        #[derive(Clone, Copy, Debug, PartialEq, Eq)]
        pub enum Key { $($key,)* }
        impl Key {
            #[cfg(test)]
            pub const ALL: &'static [Self] = &[$(Self::$key,)*];
            pub(super) fn template(self, language: Language, many: bool) -> &'static str {
                match self { $(Self::$key => {
                    $(if many { return match language { Language::English => $en_many, Language::German => $de_many }; })?
                    let _ = many;
                    match language { Language::English => $en, Language::German => $de }
                },)* }
            }
        }
    }
}
